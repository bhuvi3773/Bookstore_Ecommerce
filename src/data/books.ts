export const categorySlug = (name: string) => name.toLowerCase().replace(/\s+/g, '-').replace(/'/g, '')

export const categories = categoryMeta.map((category) => ({
  ...category,
  count: books.filter((book) => book.category === category.name).length,
}))

export const languages = Array.from(new Set(books.map((book) => book.language))).sort()
export const authors = Array.from(new Set(books.map((book) => book.author))).sort()
export const formats = Array.from(new Set(books.flatMap((book) => book.format)))

export function getBookBySlug(slug: string) {
  return books.find((book) => book.slug === slug)
}

export function getBookById(id: string) {
  return books.find((book) => book.id === id)
}

export function getBooksByCategory(category: string) {
  return books.filter((book) => book.category.toLowerCase() === category.toLowerCase())
}

export function getCategoryBySlug(slug: string) {
  return categoryMeta.find((category) => category.slug === slug || categorySlug(category.name) === slug)
}
